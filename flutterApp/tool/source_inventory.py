#!/usr/bin/env python3
"""Rebuild the immutable Kotlin baseline inventory without reading user profiles."""
import collections
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = "348b613a0c3db1a54de56483ea6f8748d6465211"
OUT = ROOT / "docs" / "flutter-rewrite"

def git(*args):
    return subprocess.check_output(["git", "-C", str(ROOT), *args])

entries = []
settings = collections.defaultdict(set)
for record in git("ls-tree", "-rlz", BASELINE).split(b"\0"):
    if not record:
        continue
    metadata, raw_path = record.split(b"\t", 1)
    mode, kind, sha, size = metadata.decode().split()
    path = raw_path.decode()
    item = {"path": path, "git_blob": sha, "bytes": int(size) if size != "-" else None}
    if path.endswith(".kt") and path.startswith(("desktopApp/", "shared/", "sharedUi/")):
        source = git("show", f"{BASELINE}:{path}").decode("utf-8", "replace")
        item["symbols"] = sorted(set(re.findall(
            r"\b(?:class|object|interface|fun|enum\s+class|data\s+class)\s+([A-Za-z_][A-Za-z0-9_]*)", source)))
        if path.startswith("desktopApp/src/main/"):
            keys = set(re.findall(r'\b(?:const\s+)?val\s+KEY[A-Z_]*\s*=\s*"([a-z][a-z0-9_]*)"', source))
            keys.update(re.findall(
                r'\b(?:preferences|persistence)\s*\.\s*(?:get|getBoolean|getInt|getFloat|put|putBoolean|putInt|putFloat|boolean|int|float|string|saveBoolean|saveInt|saveFloat|saveString)\s*\(\s*"([a-z][a-z0-9_]*)"', source))
            item["literal_preference_keys"] = sorted(keys)
            for key in keys:
                settings[key].add(path)
    entries.append(item)
OUT.mkdir(parents=True, exist_ok=True)
report = {
    "baseline_branch": "1.9.2", "baseline_commit": BASELINE,
    "method": "Full tracked-file tree, immutable Git blob IDs; Kotlin declaration and literal preference indexes are syntactic discovery aids, not semantic parity certification.",
    "tracked_files": len(entries),
    "desktop_kotlin_files": sum(e["path"].startswith("desktopApp/src/main/") and e["path"].endswith(".kt") for e in entries),
    "files": entries,
}
(OUT / "source-inventory.json").write_text(json.dumps(report, indent=2) + "\n")
lines = ["# Literal preference inventory", "", f"Baseline: `{BASELINE}` (`1.9.2`).", "",
         "Generated by `python flutterApp/tool/source_inventory.py`. This indexes literal `KEY*` declarations and direct preference calls in the actual desktop source. Dynamically constructed keys, enum constructor keys and settings held in shared models require the subsystem audit in [feature-parity.md](feature-parity.md). A key's presence in this list does not mean it has been ported. Secret **names** are indexed; no profile, value or credential is read.", "",
         "| Preference key | Source files |", "| --- | --- |"]
for key, paths in sorted(settings.items()):
    lines.append(f"| `{key}` | " + ", ".join(f"`{Path(path).name}`" for path in sorted(paths)) + " |")
(OUT / "settings-inventory.md").write_text("\n".join(lines) + "\n")
print(f"Indexed {len(entries)} tracked files, {report['desktop_kotlin_files']} desktop Kotlin files and {len(settings)} literal preference keys.")
