"""Reproduce source inventory and shell translations from the pinned Git tree.
No network, credentials, runtime profiles, or prior Flutter sources are read.
"""
from pathlib import Path
import hashlib
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SHA = '348b613a0c3db1a54de56483ea6f8748d6465211'
BASE = 'desktopApp/src/main/kotlin/com/music/bitchord/desktop/'
LANGUAGES = 'en de es fr he hi id it ja ko pl pt ru tr zh'.split()
KEYS = 'home search library history downloads settings appearance reduce_animation reduce_dynamic_blur'.split()


def read(path):
    return subprocess.check_output(['git', 'show', f'{SHA}:{path}'], cwd=ROOT.parent)


def artifacts():
    paths = subprocess.check_output(['git', 'ls-tree', '-r', '--name-only', SHA, BASE], cwd=ROOT.parent).decode().splitlines()
    sources, declarations = {}, []
    # Include all desktop preference/default and UI-state declarations with line context.
    for path in paths:
        if not path.endswith('.kt'):
            continue
        raw = read(path)
        lines = raw.decode().splitlines()
        matches = []
        for index, line in enumerate(lines):
            if re.search(r'(persistence\.|preferences\.|mutableStateOf|flag\(|enum class|contentDescription\s*=|DesktopStrings\[|DesktopEmptyPage\(|UiState\.|if \(|SettingsRow\(|SettingsToggle\()', line):
                matches.append({'line': index + 1, 'source': '\n'.join(lines[index:index + 3])})
        if matches:
            sources[path] = hashlib.sha256(raw).hexdigest()
            declarations.append({'path': path, 'declarations': matches})
    app = read(BASE + 'DesktopApp.kt').decode()
    block = app.split('internal enum class DesktopDestination')[1].split('\n}')[0]
    routes = [{'symbol': a, 'id': b, 'label': c} for a,b,c in re.findall(r'(\w+)\("([^"]+)", "([^"]+)"\)', block)]
    overlays = read(BASE + 'DesktopOverlays.kt').decode()
    inventory = {'reference': SHA, 'method': 'git show; source declarations are evidence, not evaluated defaults or runtime acceptance',
                 'routes': routes, 'overlays': re.findall(r'var (\w+) by', overlays),
                 'settings_source': app[app.index('private enum class DesktopSettingsSection'):app.index('private fun DesktopSettingsFooter')],
                 'settings_pages': re.findall(r'^    ([A-Z_]+),?$', overlays, re.M),
                 'source_sha256': sources, 'declarations': declarations}
    catalogues = {}
    for tag in LANGUAGES:
        values = {}
        for name in (tag, 'desktop-' + tag):
            path = f'desktopApp/src/main/resources/strings/{name}.xml'
            raw = read(path)
            sources[path] = hashlib.sha256(raw).hexdigest()
            for element in ET.fromstring(raw).findall('string'):
                if element.attrib['name'] in KEYS:
                    text = ''.join(element.itertext())
                    text = re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m[1],16)), text)
                    values[element.attrib['name']] = text.replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n')
        catalogues[tag] = values
    dart = '// Generated by tool/phase2_reference.py from Kotlin ' + SHA + '.\n'
    dart += '// GPL-3.0 repository resources; no fonts or personal data.\n'
    dart += '// dart format off\n'
    dart += 'const shellCatalogues = <String, Map<String, String>>{\n'
    for tag, values in catalogues.items():
        dart += "  '" + tag + "': {\n"
        for key, value in values.items():
            # JSON is a valid Dart double-quoted string after escaping interpolation.
            dart += '    ' + json.dumps(key) + ': ' + json.dumps(value, ensure_ascii=False).replace('$', '\\$') + ',\n'
        dart += '  },\n'
    dart += '};\n'
    return {ROOT/'verification/phase2/reference-inventory.json': json.dumps(inventory, ensure_ascii=False, indent=2)+'\n',
            ROOT/'lib/l10n/shell_catalogues.g.dart': dart}


def main():
    for path, expected in artifacts().items():
        if '--check' in sys.argv:
            if path.read_text() != expected:
                raise SystemExit(f'Stale reference extraction: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    print('Pinned route/state/preference/semantics inventory and 15 shell catalogues verified.')

if __name__ == '__main__':
    main()
